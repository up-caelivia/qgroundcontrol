#!/bin/bash
cd qgroundcontrol


if [ "$CLEAN" == "true" ]; then
    cd build-docker
    echo "---------------------------------------------------------------------------------------------"
    echo "----------------------------------------- Clean ---------------------------------------------"
    echo "---------------------------------------------------------------------------------------------"
    make clean
    cd ..
fi

if [ "$FAST" != "true" ]; then
    echo "---------------------------------------------------------------------------------------------"
    echo "--------------------------------------Update Custom------------------------------------------"
    echo "---------------------------------------------------------------------------------------------"
    echo ""
    cd custom
    python3 updateqrc.py
    cd ..
fi
echo "---------------------------------------------------------------------------------------------"
echo "---------------------------------------Build Start-------------------------------------------"
echo "---------------------------------------------------------------------------------------------"
echo ""
mkdir -p build-docker
cd build-docker

if [ "$FAST" != "true" ]; then
    qmake -r ../qgroundcontrol.pro -spec android-clang CONFIG+=release CONFIG+=installer ANDROID_ABIS="arm64-v8a"
fi
make -j$(nproc) apk